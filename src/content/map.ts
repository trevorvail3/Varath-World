/** Tiles that block movement (mirrors the core's walkability check). */
const BLOCKED = new Set<TileType>(["water", "mountain", "cave_wall", "deep", "wall"]);

/** A cheap, stable pseudo-noise so terrain is fixed (not random). */
function noise(x: number, y: number): number {
  const n = Math.sin(x * 157.31 + y * 113.77) * 43758.5453;
  return n - Math.floor(n);
}

// --- Region tile rules. Each takes coordinates in the region's ORIGINAL local
// space (the same numbers it always used), so the internal layout is unchanged;
// decode() maps each new-canvas tile back to those local coords. ---

function forestTile(x: number, y: number): TileType {
  if (x === 13 || x === 14) return "path"; // the Lodge road
  const fringe = x < 2 || x > 25;
  const inClearing = y >= 24 && y <= 27 && x >= 5 && x <= 22;
  if (inClearing) return "dirt";
  return fringe ? "grass" : "moss";
}

function spineTile(x: number, y: number): TileType {
  const sx = x - 28;
  if ((x === 39 || x === 40) && y >= 9 && y <= 27) return "water"; // Cold Stream
  if (sx <= 3 && y >= 5 && y <= 9) return "stone"; // the pass off the hills
  // Clumped peaks at a lower density form a few ridges with clear lanes between,
  // rather than scattered single blocks you have to thread around every step.
  const peakChance = sx < 6 ? 0.82 : 0.76;
  if (clump(x, y) > peakChance) return "mountain";
  return sx < 6 || y < 5 ? "stone" : "snow";
}

/** Coarse noise: each 2×2 block shares a value, so blockers form clumps (rock
 *  masses / ridges) rather than single-tile speckle that mazes up traversal. */
function clump(x: number, y: number): number {
  return noise(Math.floor(x / 2), Math.floor(y / 2));
}

function marrowTile(x: number, y: number): TileType {
  // Clumped walls at a lower density read as cavern walls with broad galleries
  // between them, instead of a salt-and-pepper maze.
  if (clump(x, y) > 0.66) return "cave_wall";
  return "cave";
}

function heartmoorTile(x: number, y: number): TileType {
  if (x === 13 || x === 14) return "path"; // the road continues south
  const n = noise(x, y);
  if (n > 0.84) return "water"; // bog pools (impassable)
  if (n < 0.12) return "grass"; // firmer tussocks
  return "bog";
}

function ashfenTile(x: number, y: number): TileType {
  if (noise(x, y) > 0.85) return "stone"; // warm outcrops
  return "ash";
}

function redrunTile(x: number, y: number): TileType {
  // Coastal banks — the open sea and the Redrun's mouth are carved over this in
  // decode() (the curved coastline + the cross-map river), so the region itself
  // is just the grassy/sandy ground the water laps against.
  return noise(x, y) > 0.72 ? "dirt" : "grass";
}

// --- Expanded biome frontiers (painted over open heath in decode, so the map's
// edges read as real mountains / forest / mining country rather than blank field).
/** The northern range: snowy stone highland with clumped peaks (walkable lanes). */
function northRangeTile(x: number, y: number): TileType {
  if (clump(x, y) > 0.80) return "mountain";
  return y < 16 ? "snow" : "stone";
}
/** The north-east mining hills: bare stone with the odd crag (walkable). */
function mineHillTile(x: number, y: number): TileType {
  return clump(x, y) > 0.84 ? "mountain" : "stone";
}
/** The western wood: a mossy forest floor, the odd trodden dirt patch. */
function forestFloorTile(x: number, y: number): TileType {
  return noise(x, y) > 0.82 ? "dirt" : "moss";
}

/**
 * Each wilderness region: its tile rule, the top-left of its ORIGINAL local
 * coordinate box, its size, and where that box now sits on the bigger canvas.
 * `dx/dy` (new origin − old origin) is exported so spawns.ts can shift every
 * object the same way and stay perfectly aligned with the terrain.
 */
export interface RegionPlacement {
  key: string;
  fn: (x: number, y: number) => TileType;
  ogx: number; ogy: number; // original local origin
  w: number; h: number;
  nx: number; ny: number; // new origin on the canvas
}

