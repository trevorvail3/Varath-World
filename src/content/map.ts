/** The regional architecture-palette key for a building tile, or undefined for
 *  Ironvale's default dressed stone. Read by the renderer's drawWall / drawRoof. */
export function cityPalette(x: number, y: number): string | undefined { return paletteCells.get(`${x},${y}`); }

function decode(): WorldMap {
  const tiles: TileType[] = new Array(WIDTH * HEIGHT).fill("grass");
  const set = (x: number, y: number, t: TileType) => {
    if (x >= 0 && y >= 0 && x < WIDTH && y < HEIGHT) tiles[y * WIDTH + x] = t;
  };
  const carve = (x0: number, y0: number, x1: number, y1: number, t: TileType) => {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) set(x, y, t);
  };
  // Central-complex carves: authored in LEGACY coords, shifted by CENTRAL_SHIFT
  // so they ride with the re-centred city (mirrors remap() for spawns).
  const cc = (x0: number, y0: number, x1: number, y1: number, t: TileType) =>
    carve(x0 + CDX, y0 + CDY, x1 + CDX, y1 + CDY, t);

  // 1) The arena band starts as solid wall; rooms are carved later.
  for (let y = OVERWORLD_HEIGHT; y < HEIGHT; y++) {
    for (let x = 0; x < WIDTH; x++) set(x, y, "wall");
  }

  // 2) Paint each wilderness region at its new home (same internal layout).
  for (const r of REGIONS) {
    for (let cy = r.ny; cy < r.ny + r.h; cy++) {
      for (let cx = r.nx; cx < r.nx + r.w; cx++) {
        const ox = cx - r.nx + r.ogx;
        const oy = cy - r.ny + r.ogy;
        set(cx, cy, r.fn(ox, oy));
      }
    }
  }

  // 2b) Repair any floor pocket a clump walled off, so every cavern/ledge stays
  //     reachable (it only opens blockers, never strands a spawn).
  const inRect = (x: number, y: number, x0: number, y0: number, x1: number, y1: number): boolean =>
    x >= x0 && x <= x1 && y >= y0 && y <= y1;
  const repairConnectivity = (
    x0: number, y0: number, x1: number, y1: number, floorAt: (x: number, y: number) => TileType,
  ): void => {
    const walkableHere = (x: number, y: number): boolean =>
      inRect(x, y, x0, y0, x1, y1) && !BLOCKED.has(tiles[y * WIDTH + x]!);
    const seen = new Set<number>();
    const pockets: [number, number][][] = [];
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) {
      const idx = y * WIDTH + x;
      if (!walkableHere(x, y) || seen.has(idx)) continue;
      const cells: [number, number][] = []; const q: [number, number][] = [[x, y]]; seen.add(idx);
      while (q.length) {
        const [cx, cy] = q.shift()!; cells.push([cx, cy]);
        for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
          const nx = cx + dx, ny = cy + dy, ni = ny * WIDTH + nx;
          if (walkableHere(nx, ny) && !seen.has(ni)) { seen.add(ni); q.push([nx, ny]); }
        }
      }
      pockets.push(cells);
    }
    if (pockets.length <= 1) return;
    pockets.sort((a, b) => b.length - a.length);
    const centre = (c: [number, number][]): [number, number] =>
      [Math.round(c.reduce((s, p) => s + p[0], 0) / c.length), Math.round(c.reduce((s, p) => s + p[1], 0) / c.length)];
    const [mx, my] = centre(pockets[0]!);
    for (let i = 1; i < pockets.length; i++) {
      let [cx, cy] = centre(pockets[i]!);
      let guard = 0;
      while ((cx !== mx || cy !== my) && guard++ < 200) {
        if (cx !== mx) cx += Math.sign(mx - cx);
        else if (cy !== my) cy += Math.sign(my - cy);
        if (inRect(cx, cy, x0, y0, x1, y1) && BLOCKED.has(tiles[cy * WIDTH + cx]!)) set(cx, cy, floorAt(cx, cy));
      }
    }
  };

  // 2c) Clear a yard for each region settlement (carved over the raw region
  //     terrain), so the cottages + folk sit on cleared ground at the road-edge.
  for (const s of SETTLEMENT_CLEARINGS) carve(s.x0, s.y0, s.x1, s.y1, s.floor);

  const marrow = REGIONS.find((r) => r.key === "marrow")!;
  const spine = REGIONS.find((r) => r.key === "spine")!;
  repairConnectivity(marrow.nx, marrow.ny, marrow.nx + marrow.w - 1, marrow.ny + marrow.h - 1, () => "cave");
  repairConnectivity(spine.nx, spine.ny, spine.nx + spine.w - 1, spine.ny + spine.h - 1, (x, y) => {
    const sx = (x - spine.nx + spine.ogx) - 28;
    return sx < 6 || (y - spine.ny + spine.ogy) < 5 ? "stone" : "snow";
  });

  // 3) The home Knuckle Hills wrap the city: a dirt grove + rock outcrop to the
  //    north, a lake to the south-west, open hill grass all around.
  cc(44 - 6, 38 - 14, 79 + 6, 38 - 1, "grass"); // hill apron north
  cc(50, 24, 70, 33, "dirt");   // the dirt grove (Forestry)
  cc(82, 28, 92, 38, "stone");  // the knucklestone outcrop (Mining), NE
  cc(34, 70, 43, 82, "water");  // the lake on the city's south-west flank
  cc(80, 38, 86, 67, "grass");  // east apron to the river road

  // 4) Build Ironvale at the centre (CITY/GATES are already shifted).
  //    Plaza floor: stone in the civic (west) half, dirt in the market (east).
  carve(CITY.x0, CITY.y0, CITY.x1, CITY.y1, "stone");
  cc(63, 39, 79 - 1, 67 - 1, "dirt"); // market ground (east)
  //    Wall ring.
  for (let x = CITY.x0; x <= CITY.x1; x++) { set(x, CITY.y0, "wall"); set(x, CITY.y1, "wall"); }
  for (let y = CITY.y0; y <= CITY.y1; y++) { set(CITY.x0, y, "wall"); set(CITY.x1, y, "wall"); }
  //    Main streets (a cross joining the four gates).
  cc(59, 38, 61, 67, "path"); // N–S high street
  cc(44, 51, 79, 53, "path"); // E–W high street
  //    Four gates (open the wall ring where the roads meet it).
  carve(GATES.north.x - 1, CITY.y0, GATES.north.x + 1, CITY.y0, "path");
  carve(GATES.south.x - 1, CITY.y1, GATES.south.x + 1, CITY.y1, "path");
  carve(CITY.x0, GATES.west.y - 1, CITY.x0, GATES.west.y + 1, "path");
  carve(CITY.x1, GATES.east.y - 1, CITY.x1, GATES.east.y + 1, "path");
  //    Outlying hamlets: a packed-dirt yard, then a vacant homestead lot beside.
  cc(81, 57, 90, 63, "dirt");  // Redmouth, on the Redrun's east bank
  cc(63, 72, 73, 79, "dirt");  // The Drover's Rest, on the south road
  cc(58, 13, 67, 19, "dirt");  // The Fold, in the upland Knuckle Hills
  cc(81, 64, 86, 67, "dirt");  // Redmouth homestead lot
  cc(74, 73, 79, 76, "dirt");  // Drover's Rest homestead lot
  cc(59, 8, 64, 11, "dirt");   // The Fold homestead lot
  //    Side lanes, so every building's door opens onto a street and each city
  //    quarter has real circulation instead of one bare plaza:
  cc(45, 42, 74, 42, "path");   // north lane, along the north-row forecourts
  cc(45, 63, 78, 63, "path");   // south lane, along the trade-row forecourts
  cc(48, 42, 48, 63, "path");   // west lane (Pale Record + the Stables)
  cc(75, 43, 75, 63, "path");   // east lane (the wall houses)
  cc(63, 45, 75, 46, "path");   // the market lane — stalls line both sides
  cc(70, 54, 70, 63, "path");   // the residential lane, high street → Lodge
  //    The stable paddock: packed-dirt yard beside the barn, fenced in spawns.
  cc(49, 55, 55, 61, "dirt");
  //    The buildings: each footprint becomes blocking masonry (roofed by the renderer).
  for (const b of BUILDINGS) carve(b.x0, b.y0, b.x1, b.y1, "wall");
  //    Enterable buildings: hollow rooms (wall perimeter + walkable floor) with
  //    one open doorway — carved AFTER the solid slabs so the room floor wins.
  for (const b of ENTERABLE) {
    for (let y = b.y0; y <= b.y1; y++) for (let x = b.x0; x <= b.x1; x++) {
      const edge = x === b.x0 || x === b.x1 || y === b.y0 || y === b.y1;
      set(x, y, edge ? "wall" : b.floor);
    }
    set(b.door.x, b.door.y, b.floor); // open the doorway in the wall
  }
  //    A flagged town square around the crossroads, for the fountain + crowds.
  cc(58, 50, 62, 54, "stone");

  // 4c) The Coldstep Shack — an abandoned watch shack in the far north-west,
  //     where the maps run out (The Ninth Bell questline). A ruined one-room
  //     hut: dirt floor, wall shell with the north face fallen in, doorway on
  //     the south. Roofless by design — outside the city nothing roofs walls,
  //     so it reads as long-abandoned.
  //     (carve/set take FINAL coords — cc() is only for legacy city carves.)
  //     Authored in v2 space and spread with everything else: sp() moves a
  //     rectangle's ORIGIN to the Greater World and keeps its size, so a hut
  //     stays hut-sized rather than being scaled into a hall.
  const sp = (x0: number, y0: number, x1: number, y1: number, t: TileType) => {
    const o = spread(x0, y0);
    carve(o.x, o.y, o.x + (x1 - x0), o.y + (y1 - y0), t);
  };
  const spSet = (x: number, y: number, t: TileType) => { const o = spread(x, y); set(o.x, o.y, t); };
  sp(5, 6, 11, 11, "dirt");          // the trampled yard
  sp(6, 7, 10, 10, "wall");
  sp(7, 8, 9, 9, "dirt");            // the room floor
  spSet(8, 10, "dirt");              // the south doorway
  spSet(7, 7, "dirt"); spSet(9, 7, "dirt"); // the fallen-in north face

  // 4b) Countryside features around the city (the bible's named Knuckle Hills
  //     landmarks) — shifted with the central complex.
  cc(8, 6, 14, 12, "dirt");     // Rook's Watch — a high firepit knoll
  cc(18, 8, 26, 16, "stone");   // The Knuckle — the bald stone fist
  cc(14, 18, 22, 24, "dirt");   // an ashwood grove
  cc(28, 29, 33, 34, "water");  // a hill tarn (a head-stream pool)
  cc(5, 30, 11, 36, "stone");   // The Coldvein Scar — a played-out cutting
  cc(2, 64, 8, 70, "dirt");     // The Charburner's Clearing

  // 4d) NEW POIs filling the wide open country the bigger map opened up. Each is
  //     a patch of real ground a player can find between the city and a region.
  sp(36, 40, 44, 47, "stone");    // The Wayfarers' Crossroads ruin (NW, city→greyoak/spine)
  sp(112, 46, 122, 56, "stone");  // The Old Quarry (NE, city→marrow)
  sp(110, 96, 122, 106, "grass"); // The East Commons — drovers' meadow (E, city→redrun)
  sp(96, 112, 108, 124, "dirt");  // The Gallowsfield camp (SE, city→ashfen)
  sp(36, 104, 48, 116, "bog");    // The Sunken Mile (SW, city→heartmoor)
  sp(30, 80, 42, 90, "dirt");     // The Wood-Moor Verge (W, city→greyoak)

  // 4c) Heath: give the remaining open grass a rolling, mixed texture instead of
  //     a flat green sheet (all walkable — grass / dirt / moss hill country).
  for (let y = 0; y < OVERWORLD_HEIGHT; y++) {
    for (let x = 0; x < WIDTH; x++) {
      if (tiles[y * WIDTH + x] !== "grass") continue;
      const n = noise(x, y);
      if (n > 0.86) set(x, y, "moss");
      else if (n > 0.66) set(x, y, "dirt");
      // else: stays grass
    }
  }

  // 4e) The waters: a curved coastline sweeping into the open Eyeless Sea in the
  //     south-east corner, and the great Redrun — a wide river that crosses the
  //     whole map from the northern heights down to the sea, east of the city.
  const clamp = (v: number, lo: number, hi: number) => Math.max(lo, Math.min(hi, v));
  // Coastline: for each column, the row where land gives way to sea (a curve
  //   that opens the whole SE corner to ocean). A 2-tile shallow band, then deep.
  // The coastline and the river are CURVES over the v2 canvas. Re-tuning two
  // hand-fitted formulas for a canvas 2.5× the size would be guesswork; reading
  // them through unspread() keeps the exact shape of the shore and the exact
  // meander of the Redrun, just larger — and keeps them in register with every
  // landmark, which was spread by the same factor.
  const coastV2 = (vx: number): number =>
    clamp(Math.round(172 - (vx - 96) * 1.02 + Math.sin(vx * 0.30) * 3), 92, 165);
  /** The shore row for a canvas column. */
  const coastY = (x: number): number => spread(0, coastV2(unspread(x, 0).x)).y;
  const coastFromX = spread(90, 0).x;
  for (let x = Math.max(0, coastFromX); x < WIDTH; x++) {
    const cyTop = coastY(x);
    for (let y = cyTop; y < OVERWORLD_HEIGHT; y++) {
      // The shallow band scales too, or a 2.2× world gets a shore you can step over.
      set(x, y, y <= cyTop + Math.round(SPREAD) ? "water" : "deep");
    }
  }
  // The Redrun: a meandering channel, kept east of the city, draining to the sea.
  const riverV2 = (vy: number): number => Math.round(101 + vy * 0.26 + Math.sin(vy * 0.055) * 10);
  /** The channel's column for a canvas row. */
  const riverX = (y: number): number => spread(riverV2(unspread(0, y).y), 0).x;
  const riverTo = spread(0, 146).y;
  const halfWidth = Math.round(1.5 * SPREAD);
  for (let y = 0; y < Math.min(OVERWORLD_HEIGHT, riverTo); y++) {
    const rx = riverX(y);
    if (y >= coastY(rx)) break; // it has reached the sea
    // A river 4 tiles wide on the old canvas would read as a stream on this one,
    // so its width scales with everything else.
    for (let x = rx - halfWidth; x <= rx + halfWidth + 1; x++) set(x, y, "water");
  }

  // 4e-ii) THE STRAND: a great sandy beach where the Redrun meets the Eyeless
  //   Sea. Soft ground only (grass/dirt/moss becomes sand) so roads, rock and
  //   the water itself are untouched.
  const SOFT = new Set<TileType>(["grass", "dirt", "moss"]);
  const sandIf = (x: number, y: number): void => {
    if (x < 0 || y < 0 || x >= WIDTH || y >= OVERWORLD_HEIGHT) return;
    if (SOFT.has(tiles[y * WIDTH + x]!)) set(x, y, "sand");
  };
  //   A wide strand backing the whole south-east coastline…
  for (let x = 96; x < WIDTH; x++) {
    const cyTop = coastY(x);
    for (let y = cyTop - 5; y < cyTop; y++) sandIf(x, y);
  }
  //   …opening into the big estuary beach south of the river mouth.
  for (let y = 110; y < 132; y++) {
    const rx = riverX(y);
    for (let x = rx - 6; x <= rx + 7; x++) sandIf(x, y);
  }
  //   And a few PARTIAL pond shores inland — sand on some banks, not all (the
  //   lake's south-east curve, the hill tarn's sunny side), noise-thinned so it
  //   reads as strands, not a ring.
  const fringe = (x0: number, y0: number, x1: number, y1: number, keep: (x: number, y: number) => boolean): void => {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) {
      const t = tiles[y * WIDTH + x]!;
      if (!SOFT.has(t)) continue;
      const touchesWater = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => {
        const nt = tiles[(y + dy!) * WIDTH + (x + dx!)];
        return nt === "water";
      });
      if (touchesWater && keep(x, y) && noise(x * 3.1, y * 2.7) > 0.35) set(x, y, "sand");
    }
  };
  fringe(52, 94, 66, 110, (x, y) => x + y > 158);  // the lake: SE banks only
  fringe(46, 53, 56, 62, (_x, y) => y >= 57);      // the hill tarn: south side

  // 4f) Biome frontiers: repaint the OPEN HEATH (grass/moss only — so roads,
  //     clearings, water, regions and settlements are untouched) at the map's
  //     edges into real terrain — a northern mountain range, north-east mining
  //     hills, and a great western wood. The central country stays as it is.
  const HEATH = new Set<TileType>(["grass", "moss"]);
  const paintBiome = (x0: number, y0: number, x1: number, y1: number, fn: (x: number, y: number) => TileType): void => {
    for (let y = Math.max(0, y0); y <= Math.min(OVERWORLD_HEIGHT - 1, y1); y++) {
      for (let x = Math.max(0, x0); x <= Math.min(WIDTH - 1, x1); x++) {
        if (HEATH.has(tiles[y * WIDTH + x]!)) set(x, y, fn(x, y));
      }
    }
  };
  paintBiome(0, 0, WIDTH - 1, 30, northRangeTile);   // the northern range, spanning the top
  paintBiome(102, 30, 120, 58, mineHillTile);        // NE mining hills (river ↔ Marrow)
  paintBiome(0, 40, 42, 158, forestFloorTile);       // the western wood, down the whole west
  // Keep the new blocking terrain traversable (open any walled-off pockets).
  repairConnectivity(0, 0, WIDTH - 1, 30, (_x, y) => (y < 16 ? "snow" : "stone"));
  repairConnectivity(102, 30, 120, 58, () => "stone");

  // 5) Long roads from the gates out to each far region (3 wide, walkable). The
  //    regions sit far from the centre now, so these are real journeys. Where a
  //    road meets the Redrun it carves a ford (path) straight over the water.
  const greyoak = REGIONS.find((r) => r.key === "greyoak")!;
  const ashfen = REGIONS.find((r) => r.key === "ashfen")!;
  const heartmoor = REGIONS.find((r) => r.key === "heartmoor")!;
  const redrun = REGIONS.find((r) => r.key === "redrun")!;
  const road = (x0: number, y0: number, x1: number, y1: number) => carve(x0, y0, x1, y1, "path");
  const stoneRd = (x0: number, y0: number, x1: number, y1: number) => carve(x0, y0, x1, y1, "stone");
  // North gate → the Spine pass (its walkable stone pass is at its west edge).
  road(GATES.north.x - 1, spine.ny + 14, GATES.north.x + 1, CITY.y0 - 1); // up to the pass
  road(spine.nx + 2, spine.ny + 13, GATES.north.x + 1, spine.ny + 15);    // west along to the pass foot
  stoneRd(spine.nx, spine.ny + 5, spine.nx + 3, spine.ny + 16);           // into the Spine pass
  // West gate → Greyoak Wood (its Lodge road is at local x13–14 → canvas nx+13).
  road(greyoak.nx + 14, GATES.west.y - 1, CITY.x0 - 1, GATES.west.y + 1);
  // South gate → Ashfen Flats via a long moor road.
  road(GATES.south.x - 1, CITY.y1 + 1, GATES.south.x + 1, ashfen.ny);
  road(ashfen.nx + 8, ashfen.ny - 2, GATES.south.x + 1, ashfen.ny);
  // South-west spur → Heartmoor (its road is at local x13–14 → canvas nx+13).
  road(heartmoor.nx + 14, GATES.south.y, heartmoor.nx + 16, heartmoor.ny); // down the moor
  road(heartmoor.nx + 14, GATES.south.y, GATES.south.x, GATES.south.y + 2); // link to the south road
  // East gate → the Redrun & the river road.
  road(CITY.x1 + 1, GATES.east.y - 1, redrun.nx, GATES.east.y + 1);       // east across the commons
  road(redrun.nx - 1, GATES.east.y, redrun.nx + 1, redrun.ny);            // down to the riverbank
  // North-east spur → the Marrow Deeps cave mouth (an L: up the outcrop, then
  //    across to the cave). carve() only fills left→right / top→down, so keep
  //    each leg's corners ordered.
  stoneRd(CITY.x1, marrow.ny + 15, CITY.x1 + 2, GATES.east.y);            // up from the east road
  stoneRd(CITY.x1, marrow.ny + 15, marrow.nx, marrow.ny + 16);           // across to the outcrop
  carve(marrow.nx, marrow.ny + 12, marrow.nx + 3, marrow.ny + 16, "cave"); // into the cave mouth

  // 5b) Short lanes joining the outlying hamlets to the road network.
  cc(84, 54, 85, 57, "path");   // Redmouth lane up to the east road
  cc(61, 75, 64, 76, "path");   // The Drover's Rest, off the south road
  cc(58, 19, 60, 24, "path");   // The Fold, down to the grove
  //     The fishers' track: Redmouth is a FISHING hamlet, so a worn track runs
  //     from its yard east to the Redrun bank, onto a short plank jetty over the
  //     water (canvas coords — the river is carved in final space). The boat and
  //     net-racks stand at its head (spawns.ts).
  cc(86, 60, 91, 60, "path");                       // yard → riverbank
  { // the fishers' jetty — authored in v2 space, spread with the river it reaches
    const j0 = spread(110, 86), j1 = spread(114, 86);
    for (let px = j0.x; px <= j1.x; px++) set(px, j0.y, "plank");
  }

  // 5c) Ecotone dither — feather the seams between open-wilderness biomes so
  //     they roll into one another instead of cutting hard on the grid. Rather
  //     than blurring colours (which just reads as out-of-focus), we keep every
  //     tile crisp and scatter actual tiles of the neighbouring biome across a
  //     ~3-tile band, thinning out with distance from the seam — the way pixel
  //     terrain blends. Grassland speckles into the mountain foot, the forest
  //     floor, the mine hills and the moor, and vice-versa. Only wild ground is
  //     touched: designed areas (the regions, the city), roads and water are
  //     left intact, and swaps stay within walkable ground so nothing is sealed.
  {
    const CONVERT = new Set<TileType>(["grass", "dirt", "moss", "bog", "ash", "snow"]);
    const TARGET = new Set<TileType>(["grass", "dirt", "moss", "bog", "ash", "snow", "stone"]);
    const ECO_R = 4;
    const inDesigned = (x: number, y: number): boolean => {
      if (x >= CITY.x0 - 1 && x <= CITY.x1 + 1 && y >= CITY.y0 - 1 && y <= CITY.y1 + 1) return true;
      for (const r of REGIONS) {
        if (x >= r.nx && x < r.nx + r.w && y >= r.ny && y < r.ny + r.h) return true;
      }
      return false;
    };
    const src = tiles.slice(); // snapshot so swaps don't cascade across the band
    for (let y = 0; y < OVERWORLD_HEIGHT; y++) {
      for (let x = 0; x < WIDTH; x++) {
        const t = src[y * WIDTH + x]!;
        if (!CONVERT.has(t) || inDesigned(x, y)) continue;
        // Nearest differing target biome within the band (Manhattan distance).
        let best: TileType | null = null;
        let bestD = ECO_R + 1;
        for (let dy = -ECO_R; dy <= ECO_R; dy++) {
          for (let dx = -ECO_R; dx <= ECO_R; dx++) {
            const d = Math.abs(dx) + Math.abs(dy);
            if (d === 0 || d > ECO_R) continue;
            const nx = x + dx, ny = y + dy;
            if (nx < 0 || ny < 0 || nx >= WIDTH || ny >= OVERWORLD_HEIGHT) continue;
            const nt = src[ny * WIDTH + nx]!;
            if (nt !== t && TARGET.has(nt) && d < bestD) { bestD = d; best = nt; }
          }
        }
        if (!best) continue;
        const p = 0.62 * (1 - (bestD - 1) / ECO_R); // densest at the seam, fading out
        if (noise(x * 1.93 + 11, y * 1.71 + 7) < p) set(x, y, best);
      }
    }
  }

  // 6) Carve the sealed boss arenas in the band below the overworld.
  for (const a of ARENAS) {
    for (let y = ARENA_TOP; y < ARENA_TOP + ARENA_H; y++) {
      for (let x = a.x; x < a.x + ARENA_W; x++) {
        const edge = x === a.x || x === a.x + ARENA_W - 1 || y === ARENA_TOP || y === ARENA_TOP + ARENA_H - 1;
        set(x, y, edge ? "wall" : a.floor);
      }
    }
  }

  // 7) Carve each player-home interior in the band below the arenas.
  for (const h of HOMES) {
    const plan = homeLayout(h.ox);
    for (const rm of plan.rooms) {
      for (let y = rm.y0; y <= rm.y1; y++) {
        for (let x = rm.x0; x <= rm.x1; x++) {
          const edge = x === rm.x0 || x === rm.x1 || y === rm.y0 || y === rm.y1;
          set(x, y, edge ? "wall" : "plank");
        }
      }
    }
    for (const d of plan.doorways) set(d.x, d.y, "plank"); // openings (incl. the sealed wing doorway)
  }

  // 7c) Carve the Act II dungeon sites from their hand-authored ASCII layouts
  //     (content/dungeons.ts). Each site's bounding box is first set to cave
  //     wall so the halls read as hewn rock, then the floors are carved.
  const DUNGEON_TILE: Record<string, TileType> = { "#": "cave_wall", ".": "cave", ",": "dirt", "~": "water" };
  for (const site of DUNGEONS) {
    for (let ty = site.y0 - 1; ty <= site.y0 + site.h; ty++) {
      for (let tx = site.x0 - 1; tx <= site.x0 + site.w; tx++) set(tx, ty, "cave_wall");
    }
    site.rows.forEach((row, r) => {
      for (let c = 0; c < row.length; c++) {
        const t = DUNGEON_TILE[row[c]!];
        if (t) set(site.x0 + c, site.y0 + r, t);
      }
    });
  }

  // 7b) Carve each home's backyard paddock: a grass yard with a solid border
  //     (rendered as a fence) so pets roam a bounded, outdoor-looking pen.
  for (const y of BACKYARDS) {
    for (let ty = y.y0; ty <= y.y1; ty++) {
      for (let tx = y.x0; tx <= y.x1; tx++) {
        const edge = tx === y.x0 || tx === y.x1 || ty === y.y0 || ty === y.y1;
        set(tx, ty, edge ? "wall" : "grass");
      }
    }
    set(y.gate.x, y.gate.y, "grass"); // the return gate stands on grass
  }

  // 8) The Drowned Pier: a plank jetty off the Redrun estuary, reaching from the
  //    SE shore out over the deep. A single-tile neck (its only land approach is
  //    from the north, water on both sides) lets one barrier gate the whole pier
  //    until the warden's quest is done. The cast point at (148,124) is left as
  //    open deep water; the player fishes it from the plank end. (Canvas coords.)
  for (const [px, py] of PIER.planks) set(px, py, "plank");

  return { name: "Varath", width: WIDTH, height: HEIGHT, tiles };
}

/** The Drowned Pier off the Redrun estuary — fixed canvas coords shared by the
 *  map carve (the plank jetty), the spawns (warden, gate, cast point, board) and
 *  the renderer. The cast point sits on open deep water just past the plank end;
 *  the gate sits on the single-tile neck so it bars the whole pier until the
 *  warden's quest is done. */
/** The Drowned Pier off the Redrun estuary. Authored in v2 space and spread onto
 *  the Greater World like everything else, so the jetty still reaches the water
 *  the river now runs through. Shared by the map carve, the spawns (warden,
 *  gate, cast point, board) and the renderer. */
// The pier is a WALKWAY. Spreading each plank on its own would leave 2-tile
// gaps between them and turn a jetty into stepping stones, so only its anchor
// moves: the deck is then laid out contiguously from there, and its length
// scales, because the shore-to-deep-water distance scaled with everything else.
const PIER_ANCHOR = spread(148, 120);
const DECK = Math.max(4, Math.round(4 * SPREAD));
export const PIER = {
  /** Water/deep tiles carved to walkable plank decking: the deck, then two arms. */
  planks: [
    ...Array.from({ length: DECK }, (_, i) => [PIER_ANCHOR.x, PIER_ANCHOR.y + i] as [number, number]),
    [PIER_ANCHOR.x - 1, PIER_ANCHOR.y + DECK - 1] as [number, number],
    [PIER_ANCHOR.x + 1, PIER_ANCHOR.y + DECK - 1] as [number, number],
  ],
  /** The neck tile (only land approach is from the north) — the barrier sits here. */
  gate: { x: PIER_ANCHOR.x, y: PIER_ANCHOR.y },
  /** The plank tile the player stands on to fish + read the board. */
  stand: { x: PIER_ANCHOR.x, y: PIER_ANCHOR.y + DECK - 1 },
  /** Open deep water just past the deck — the cast point (left un-carved). */
  cast: { x: PIER_ANCHOR.x, y: PIER_ANCHOR.y + DECK },
  /** The records board, on a plank arm of the platform. */
  board: { x: PIER_ANCHOR.x - 1, y: PIER_ANCHOR.y + DECK - 1 },
  /** The pier-warden NPC, on the shore by the neck. */
  warden: { x: PIER_ANCHOR.x - 2, y: PIER_ANCHOR.y - 2 },
  /** A signpost at the pier head. */
  sign: { x: PIER_ANCHOR.x - 1, y: PIER_ANCHOR.y - 1 },
} as const;

export const map: WorldMap = decode();

/** A bounded "instance" rectangle (inclusive tile bounds) for view isolation. */
export interface InstanceRect { x0: number; y0: number; x1: number; y1: number }

/**
 * The instance the given tile belongs to — a player home or a boss arena — or
 * null for the open overworld. The renderer uses this to show ONLY the current
 * instance (a sealed room), so you never see the neighbouring rooms or the
 * arena band around it.
 */
export function instanceRectAt(x: number, y: number): InstanceRect | null {
  if (y < OVERWORLD_HEIGHT) return null; // the overworld is never masked
  for (const h of HOMES) {
    if (x >= h.ox && x <= h.ox + HOUSE_W - 1 && y >= INTERIOR_TOP && y <= INTERIOR_TOP + 10) {
      return { x0: h.ox, y0: INTERIOR_TOP, x1: h.ox + HOUSE_W - 1, y1: INTERIOR_TOP + 10 };
    }
  }
  for (const b of BACKYARDS) {
    if (x >= b.x0 && x <= b.x1 && y >= b.y0 && y <= b.y1) {
      return { x0: b.x0, y0: b.y0, x1: b.x1, y1: b.y1 };
    }
  }
  for (const d of DUNGEONS) {
    if (x >= d.x0 - 1 && x <= d.x0 + d.w && y >= d.y0 - 1 && y <= d.y0 + d.h) {
      return { x0: d.x0 - 1, y0: d.y0 - 1, x1: d.x0 + d.w, y1: d.y0 + d.h };
    }
  }
  for (const a of ARENAS) {
    if (x >= a.x && x <= a.x + ARENA_W - 1 && y >= ARENA_TOP && y <= ARENA_TOP + ARENA_H - 1) {
      return { x0: a.x, y0: ARENA_TOP, x1: a.x + ARENA_W - 1, y1: ARENA_TOP + ARENA_H - 1 };
    }
  }
  return null;
}

/** Convenience: read the tile type at a coordinate (grass if out of bounds). */
export function tileAt(m: WorldMap, x: number, y: number): TileType {
  if (x < 0 || y < 0 || x >= m.width || y >= m.height) return "grass";
  return m.tiles[y * m.width + x]!;
}
